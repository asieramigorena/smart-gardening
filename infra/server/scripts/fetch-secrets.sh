#!/usr/bin/env bash
# Write /opt/smart-gardening/.env from SSM Parameter Store, for docker compose.
#
# Runs on the server as root (deploy.sh calls it). Uses the EC2 instance role: no keys needed.
# The role cannot read the devices' private keys, and this script does not need them: it asks
# for an explicit list of parameters instead of the whole /smart-gardening path.
#
# Usage: sudo fetch-secrets.sh [output_file]
set -euo pipefail

OUT="${1:-/opt/smart-gardening/.env}"

# Region of the instance, from IMDSv2 (unless AWS_REGION is already set).
if [[ -z "${AWS_REGION:-}" ]]; then
  token=$(curl -fsS -X PUT http://169.254.169.254/latest/api/token \
    -H 'X-aws-ec2-metadata-token-ttl-seconds: 60')
  AWS_REGION=$(curl -fsS -H "X-aws-ec2-metadata-token: $token" \
    http://169.254.169.254/latest/meta-data/placement/region)
fi
export AWS_REGION

# ENV_VAR=SSM parameter
PARAMETERS=(
  POSTGRES_PASSWORD=/smart-gardening/db/password
  DB_APP_PASSWORD=/smart-gardening/db/app_password
  DB_GRAFANA_PASSWORD=/smart-gardening/db/grafana_password
  GRAFANA_ADMIN_PASSWORD=/smart-gardening/grafana/admin_password
  IOT_ENDPOINT=/smart-gardening/iot/endpoint
  INGEST_QUEUE_URL=/smart-gardening/ingest/queue_url
  INGEST_DLQ_URL=/smart-gardening/ingest/dlq_url
)

names=()
for entry in "${PARAMETERS[@]}"; do names+=("${entry#*=}"); done

# One call (max 10 names). JSON: [ [missing names...], [[name, value], ...] ]
response=$(aws ssm get-parameters --names "${names[@]}" --with-decryption \
  --query '[InvalidParameters, Parameters[].[Name, Value]]' --output json)

missing=$(jq -r '.[0][]' <<<"$response")
if [[ -n "$missing" ]]; then
  echo "error: missing SSM parameters: ${missing//$'\n'/ }" >&2
  exit 1
fi

tmp=$(mktemp "$(dirname "$OUT")/.env.XXXXXX")
trap 'rm -f "$tmp"' EXIT
chmod 600 "$tmp"
{
  echo "# Generated by fetch-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit or commit."
  echo "AWS_REGION=$AWS_REGION"
  for entry in "${PARAMETERS[@]}"; do
    var="${entry%%=*}"
    name="${entry#*=}"
    value=$(jq -r --arg n "$name" '.[1][] | select(.[0] == $n) | .[1]' <<<"$response")
    # Values are URL-safe passwords, URLs and hostnames; refuse anything that would need quoting.
    if [[ ! "$value" =~ ^[A-Za-z0-9._:/@-]+$ ]]; then
      echo "error: unexpected characters in $name" >&2
      exit 1
    fi
    echo "$var=$value"
  done
} >"$tmp"
mv "$tmp" "$OUT"
trap - EXIT
echo "wrote $OUT (${#PARAMETERS[@]} parameters, mode 600)"
